"""A fixed educational exhibition of original mathematical art and music."""
from __future__ import annotations

import argparse
import base64
from html import escape
import json

from .mathematical_art import render_polygon
from .mathematical_rhythm import render_rhythm_svg
from .harmonic_geometry import render_harmonic_svg
from .fourier_art import render_fourier_svg
from .nature_mathematics import render_phyllotaxis_svg
from .tessellation_art import render_tessellation_svg
from .fractal_art import fractal_study
from .cellular_art import cellular_study
from .rhythm_sonification import rhythm_wav
from .palette_melody import palette_wav

MEDIA_TYPES = ("image/svg+xml", "image/png", "audio/wav")


def creative_universe() -> dict:
    """Curated fixed fixtures, generated locally with no source-file inputs."""
    exhibits = []

    def add(identifier, title, medium, description, payload):
        if isinstance(payload, str):
            payload = payload.encode("utf-8")
        exhibits.append({
            "id": identifier,
            "title": title,
            "media_type": medium,
            "description": description,
            "media_base64": base64.b64encode(payload).decode("ascii"),
        })

    add("polygon72", "Mathematics 72", "image/svg+xml",
        "Regular polygon with 72 sides and unit circumradius.",
        render_polygon(72))
    add("rhythm72", "Circular rhythm", "image/svg+xml",
        "Eight evenly spaced pulses in a 72-step grid.",
        render_rhythm_svg(72, 8))
    add("harmonic23", "Harmonic geometry", "image/svg+xml",
        "Ideal Lissajous curve, 2:3 ratio and 90-degree phase.",
        render_harmonic_svg(2, 3, 1))
    add("fourier9", "Fourier art", "image/svg+xml",
        "Square wave approximation using nine odd harmonics.",
        render_fourier_svg(9))
    add("phyllotaxis144", "Nature mathematics", "image/svg+xml",
        "144 points on an idealized golden-angle disk.",
        render_phyllotaxis_svg(144))
    add("hexagons", "Regular tessellation", "image/svg+xml",
        "Finite illustration of a regular hexagonal tiling.",
        render_tessellation_svg("hexagon"))
    add("mandelbrot", "Fractal universe", "image/png",
        "Fixed-view 128 x 128 escape-time illustration, 48 iterations.",
        fractal_study(128, 48)[1])
    add("rule30", "Emergent art", "image/png",
        "Rule 30 binary artwork, 145 cells and 72 rows.",
        cellular_study(30, 145, 72)[1])
    add("pulse_music", "Rhythm sonification", "audio/wav",
        "Original 72-step pulse audio, one cycle at 120 BPM.",
        rhythm_wav(72, 8, bpm=120, cycles=1))
    add("dusk_melody", "Palette melody", "audio/wav",
        "Original three-note melody from the fixed dusk palette.",
        palette_wav("dusk"))
    return {
        "schema": "klone.creative_universe_exhibition.v1",
        "exhibits": exhibits,
        "limitations": [
            "Fixed educational exhibition of original synthetic artworks and audio.",
            "All media are generated by the selected local creative modules.",
            "No external assets, input files, network services or automatic playback.",
            "No comparison of aesthetic merit or inference about people.",
            "Mathematical illustrations are not independent scientific proofs.",
        ],
    }


def render_exhibition(report: dict) -> str:
    cards = []
    for item in report["exhibits"]:
        medium = item["media_type"]
        if medium not in MEDIA_TYPES:
            raise ValueError("Unsupported exhibition medium")
        title = escape(item["title"], quote=True)
        description = escape(item["description"])
        encoded = base64.b64encode(base64.b64decode(
            item["media_base64"], validate=True)).decode("ascii")
        uri = "data:" + medium + ";base64," + encoded
        if medium == "audio/wav":
            media = ("<audio controls preload='none' aria-label='" + title
                     + "' src='" + uri + "'>Audio playback unavailable.</audio>")
        else:
            media = "<img alt='" + title + "' src='" + uri + "'>"
        cards.append("<article><h2>" + title + "</h2>" + media
                     + "<p>" + description + "</p></article>")
    return (
        "<!doctype html><html lang='en'><head><meta charset='utf-8'>"
        "<meta name='viewport' content='width=device-width, initial-scale=1'>"
        "<title>KLONE Creative Universe</title><style>"
        ":root{color-scheme:light dark}*{box-sizing:border-box}"
        "body{font:16px/1.5 system-ui,sans-serif;max-width:76rem;margin:1rem auto;padding:0 1rem}"
        ".gallery{display:grid;grid-template-columns:repeat(auto-fit,minmax(min(100%,17rem),1fr));gap:1rem}"
        "article{min-width:0;border:1px solid #888;border-radius:.75rem;padding:1rem}"
        "img{display:block;width:100%;height:auto;max-height:24rem;object-fit:contain}"
        "audio{width:100%;max-width:100%}h2{font-size:1.2rem}"
        "</style></head><body><main><h1>KLONE Creative Universe</h1>"
        "<p>Mathematical art and original music: a curated offline exhibition.</p>"
        "<div class='gallery'>" + "".join(cards) + "</div>"
        "<h2>Limitations</h2><ul>"
        + "".join("<li>" + escape(s) + "</li>" for s in report["limitations"])
        + "</ul></main></body></html>"
    )


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--format", choices=("json", "html"), default="html")
    args = parser.parse_args(argv)
    report = creative_universe()
    print(render_exhibition(report) if args.format == "html"
          else json.dumps(report, indent=2, allow_nan=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
